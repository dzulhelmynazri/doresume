import { GROVE_SECTIONS } from "./grove-sections";
import type { JobSection } from "./grove-sections";

export const JOB_STATUSES = [
  "submitted",
  "in-flight",
  "needs-you",
  "failed",
  "skipped",
] as const;

export type JobStatus = (typeof JOB_STATUSES)[number];

export const RESUME_STATUSES = ["not-ready", "generating", "ready"] as const;

export type ResumeStatus = (typeof RESUME_STATUSES)[number];

export interface Job {
  appliedAt: string;
  category: string;
  company: string;
  employmentType: string;
  experience: string;
  id: string;
  location: string;
  matchPercent: number;
  resumeStatus: ResumeStatus;
  salaryMax: number;
  salaryMin: number;
  sections: JobSection[];
  seniority: string;
  status: JobStatus;
  title: string;
  url: string;
  workplace: string;
}

const formatThousands = (value: number) => `${Math.round(value / 1000)}k`;

export const formatSalaryRange = (min: number, max: number): string =>
  `USD ${formatThousands(min)} - ${formatThousands(max)} /yr`;

export const formatMatchPercent = (value: number): string => `${value}%`;

export const formatWorkplaceLocation = (
  location: string,
  workplace: string
): string => {
  if (workplace === location) {
    return location;
  }

  return `${workplace} · ${location}`;
};

export const FEATURED_JOB_COUNT = 5;
export const BROWSE_JOB_COUNT = 20;

const getTopJobs = (allJobs: Job[], count: number): Job[] =>
  allJobs
    .toSorted((left, right) => right.matchPercent - left.matchPercent)
    .slice(0, count);

export const getFeaturedJobs = (allJobs: Job[]): Job[] =>
  getTopJobs(allJobs, FEATURED_JOB_COUNT);

export const getBrowseJobs = (allJobs: Job[]): Job[] =>
  getTopJobs(
    allJobs.filter((job) => job.status !== "skipped"),
    BROWSE_JOB_COUNT
  );

export const getJobApplicationPath = (id: string): string =>
  `/dashboard/applications/${id}`;

